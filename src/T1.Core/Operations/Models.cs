using System.Text.Json.Serialization;

namespace T1.Core.Operations;

/// <summary>Content of t1.message (jsonb).</summary>
public sealed record OperationMessage(
    [property: JsonPropertyName("account_number")] string AccountNumber,
    [property: JsonPropertyName("client_id")] long ClientId,
    [property: JsonPropertyName("operation_type")] string OperationType);

/// <summary>A row of t1.</summary>
public sealed record Operation(long Id, DateTime OpDate, decimal Amount, short State, Guid OperationGuid, OperationMessage Message);

/// <summary>Arguments of t1_add_operation(); every null value is generated by the database.</summary>
public sealed record NewOperation(
    decimal? Amount = null,
    long? ClientId = null,
    string? OperationType = null,
    string? AccountNumber = null,
    Guid? OperationGuid = null,
    DateTime? OpDate = null);

/// <summary>Result of t1_confirm_operations().</summary>
public sealed record ConfirmResult(int SecondOfMinute, string Parity, long ConfirmedCount);

/// <summary>A row of the materialized view t1_client_totals.</summary>
public sealed record ClientTotal(long ClientId, string OperationType, decimal TotalAmount, long OperationsCount);

public sealed record ClientTotalsSummary(long Rows, decimal TotalAmount, long OperationsCount);

/// <summary>Aggregates of t1 on one instance.</summary>
public sealed record TableSnapshot(long Rows, long PendingRows, long ConfirmedRows, long? MaxId, decimal TotalAmount, DateTime? MinOpDate, DateTime? MaxOpDate);

public static class OperationTypes
{
    public const string Online = "online";
    public const string Offline = "offline";

    public static bool IsValid(string? value) => value is Online or Offline;
}
